def load_json(path: Path) -> Any | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return None


def normalized_path(value: object) -> Path | None:
    if not isinstance(value, str) or not value.startswith("/"):
        return None
    return Path(os.path.normpath(os.path.expanduser(value)))


def claude_project_key(path: Path) -> str:
    """Return Claude's project-directory encoding for an absolute path."""
    return re.sub(r"[^A-Za-z0-9]", "-", str(path))


def add_path_mapping(mapping: dict[str, Path], value: object) -> None:
    path = normalized_path(value)
    if path is not None:
        mapping.setdefault(claude_project_key(path), path)


def collect_index_paths(claude_home: Path) -> dict[str, Path]:
    """Build project-key to cwd mappings from Claude's metadata stores."""
    mapping: dict[str, Path] = {}
    projects_dir = claude_home / "projects"

    if projects_dir.is_dir():
        for index_path in sorted(projects_dir.glob("*/sessions-index.json")):
            data = load_json(index_path)
            if not isinstance(data, dict):
                continue
            original = normalized_path(data.get("originalPath"))
            if original is not None:
                mapping[index_path.parent.name] = original
                add_path_mapping(mapping, original)
            entries = data.get("entries", [])
            if isinstance(entries, list):
                for entry in entries:
                    if isinstance(entry, dict):
                        add_path_mapping(mapping, entry.get("projectPath"))

    sessions_dir = claude_home / "sessions"
    if sessions_dir.is_dir():
        for session_path in sorted(sessions_dir.glob("*.json")):
            data = load_json(session_path)
            if isinstance(data, dict):
                add_path_mapping(mapping, data.get("cwd"))

    history_path = claude_home / "history.jsonl"
    for item in iter_jsonl(history_path):
        add_path_mapping(mapping, item.get("project"))
        add_path_mapping(mapping, item.get("cwd"))

    config = load_json(claude_home.parent / ".claude.json")
    if isinstance(config, dict) and isinstance(config.get("projects"), dict):
        for project_path in config["projects"]:
            add_path_mapping(mapping, project_path)

    return mapping


def iter_jsonl(path: Path, limit: int | None = None) -> Iterable[dict[str, Any]]:
    try:
        with path.open(encoding="utf-8") as handle:
            for number, line in enumerate(handle):
                if limit is not None and number >= limit:
                    break
                try:
                    item = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if isinstance(item, dict):
                    yield item
    except (OSError, UnicodeDecodeError):
        return


def transcript_cwd(project_dir: Path) -> Path | None:
    """Recover cwd from a local transcript when no index entry exists."""
    for transcript in sorted(project_dir.glob("*.jsonl"), reverse=True):
        for item in iter_jsonl(transcript, limit=200):
            for key in ("cwd", "projectPath"):
                path = normalized_path(item.get(key))
                if path is not None:
                    return path
    return None


def selected(project: ProjectMemory, filters: list[str]) -> bool:
    if not filters:
        return True
    cwd = os.path.normpath(str(project.cwd))
    return any(value == project.key or os.path.normpath(value) == cwd for value in filters)


def discover_projects(
    claude_home: Path, filters: list[str]
) -> tuple[list[ProjectMemory], list[str], set[str]]:
    projects_dir = claude_home / "projects"
    if not projects_dir.is_dir():
        raise SystemExit(f"Claude projects directory does not exist: {projects_dir}")

    mapping = collect_index_paths(claude_home)
    projects: list[ProjectMemory] = []
    warnings: list[str] = []
    unresolved_keys: set[str] = set()

    for memory_dir in sorted(projects_dir.glob("*/memory")):
        if not memory_dir.is_dir() or memory_dir.is_symlink():
            continue
        files = tuple(
            path
            for path in sorted(memory_dir.rglob("*.md"))
            if path.is_file()
            and not path.is_symlink()
            and path.relative_to(memory_dir).as_posix() != CODEX_MEMORY_NAME
        )
        if not files:
            continue

        project_dir = memory_dir.parent
        key = project_dir.name
        if not PROJECT_KEY_RE.fullmatch(key):
            warnings.append(f"skip unsafe project key: {key!r}")
            continue
        cwd = mapping.get(key) or transcript_cwd(project_dir)
        if cwd is None:
            unresolved_keys.add(key)
            if not filters or key in filters:
                warnings.append(
                    f"skip {key}: cannot determine cwd from Claude indexes or transcripts"
                )
            continue

        project = ProjectMemory(key, cwd, memory_dir, files)
        if selected(project, filters):
            projects.append(project)

    return projects, warnings, unresolved_keys


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def atomic_write(path: Path, data: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as handle:
        temporary = Path(handle.name)
        handle.write(data)
        handle.flush()
        os.fsync(handle.fileno())
    try:
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def sync_file(path: Path, data: bytes, dry_run: bool, verbose: bool, stats: SyncStats) -> None:
    existing = None
    try:
        existing = path.read_bytes()
    except FileNotFoundError:
        pass
    except OSError as error:
        raise SystemExit(f"cannot read target {path}: {error}") from error

    if existing == data:
        stats.unchanged += 1
        if verbose:
            print(f"unchanged {path}")
        return

    action = "create" if existing is None else "update"
    if action == "create":
        stats.created += 1
    else:
        stats.updated += 1
    print(f"{action} {path}") if verbose or dry_run else None
    if not dry_run:
        atomic_write(path, data)


def safe_target(base: Path, relative: Path) -> Path:
    target = base / relative
    try:
        target.resolve(strict=False).relative_to(base.resolve(strict=False))
    except ValueError as error:
        raise SystemExit(f"refusing target outside import root: {target}") from error
    return target


def strip_codex_link(content: str) -> str:
    if CODEX_LINK_START not in content or CODEX_LINK_END not in content:
        return content
    pattern = re.compile(
        rf"\n*{re.escape(CODEX_LINK_START)}.*?{re.escape(CODEX_LINK_END)}\n*",
        re.DOTALL,
    )
    stripped = pattern.sub("\n", content).rstrip()
    return f"{stripped}\n" if stripped else ""


def source_memory_bytes(source: Path, relative: Path) -> bytes:
    data = source.read_bytes()
    if relative.as_posix() != "MEMORY.md":
        return data
    try:
        return strip_codex_link(data.decode("utf-8")).encode()
    except UnicodeDecodeError:
        return data


def codex_task_groups(content: str) -> dict[Path, list[str]]:
    """Group consolidated Codex task blocks by their explicit cwd scope."""
    starts = list(re.finditer(r"(?m)^# Task Group: .+$", content))
    grouped: dict[Path, list[str]] = {}
    for index, match in enumerate(starts):
        end = starts[index + 1].start() if index + 1 < len(starts) else len(content)
        block = content[match.start() : end].strip()
        scope = re.search(r"(?m)^applies_to:\s*cwd=(.*?);(?:\s|$)", block)
        cwd = normalized_path(scope.group(1).strip()) if scope else None
        if cwd is not None:
            grouped.setdefault(cwd, []).append(block)
    return grouped


def render_codex_memory(cwd: Path, blocks: list[str]) -> bytes:
    demoted = [
        re.sub(r"(?m)^(#{1,5})(?= )", lambda match: f"{match.group(1)}#", block)
        for block in blocks
    ]
    content = (
        "# Codex Memory\n\n"
        f"{CODEX_MEMORY_MARKER}\n\n"
        f"Project scope: `{cwd}`\n\n"
        "This file contains consolidated, project-scoped memory exported from "
        "Codex CLI.\n\n"
        + "\n\n".join(demoted)
        + "\n"
    )
    return content.encode()


def with_codex_link(content: str) -> str:
    base = strip_codex_link(content).rstrip()
    return f"{base}\n\n{CODEX_LINK_BLOCK}\n" if base else f"{CODEX_LINK_BLOCK}\n"


def sync_owned_file(
    path: Path, data: bytes, dry_run: bool, verbose: bool, stats: SyncStats
) -> None:
    try:
        existing = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        existing = None
    except (OSError, UnicodeDecodeError) as error:
        raise SystemExit(f"cannot read reverse-sync target {path}: {error}") from error
    if existing is not None and CODEX_MEMORY_MARKER not in existing:
        raise SystemExit(
            f"refusing to overwrite non-tool-owned reverse-sync target: {path}"
        )
    sync_file(path, data, dry_run, verbose, stats)


def load_manifest(path: Path) -> set[str]:
    data = load_json(path)
    if not isinstance(data, dict) or not isinstance(data.get("files"), list):
        return set()
    return {value for value in data["files"] if isinstance(value, str)}


def load_reverse_manifest(path: Path) -> set[str]:
    data = load_json(path)
    if not isinstance(data, dict) or not isinstance(data.get("projects"), list):
        return set()
    return {value for value in data["projects"] if isinstance(value, str)}


def remove_empty_parents(path: Path, stop: Path) -> None:
    parent = path.parent
    while parent != stop:
        try:
            parent.rmdir()
        except OSError:
            break
        parent = parent.parent


def run_to_codex(args: argparse.Namespace) -> int:
    claude_home = args.claude_home.expanduser().resolve()
    codex_home = args.codex_home.expanduser().resolve()
    projects, warnings, unresolved_keys = discover_projects(claude_home, args.project)
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)

    extension = codex_home / "memories" / "extensions" / "external_agent_import"
    resources = extension / "resources"
    manifest_path = extension / MANIFEST_NAME
    old_manifest = load_manifest(manifest_path)
    stats = SyncStats(projects=len(projects), skipped=len(warnings))
    desired: dict[str, bytes] = {}

    for project in projects:
        scope = json.dumps(
            {"cwd": str(project.cwd)}, ensure_ascii=False, indent=2, sort_keys=True
        ).encode() + b"\n"
        desired[f"{project.key}/scope.json"] = scope
        for source in project.files:
            relative = source.relative_to(project.source_dir)
            desired[(Path(project.key) / relative).as_posix()] = source_memory_bytes(
                source, relative
            )

    if not projects and args.project:
        print("No matching Claude project memories found.", file=sys.stderr)
        return 1

    sync_file(
        extension / "instructions.md",
        EXTENSION_INSTRUCTIONS.encode(),
        args.dry_run,
        args.verbose,
        stats,
    )
    for relative, data in desired.items():
        sync_file(
            safe_target(resources, Path(relative)),
            data,
            args.dry_run,
            args.verbose,
            stats,
        )

    selected_keys = {project.key for project in projects}
    managed_files = set(desired)
    managed_files.update(
        relative
        for relative in old_manifest
        if relative.partition("/")[0] in unresolved_keys
    )
    if args.project:
        managed_files.update(
            relative
            for relative in old_manifest
            if relative.partition("/")[0] not in selected_keys
        )
    if not args.delete:
        managed_files.update(old_manifest)

    if args.delete:
        for relative in sorted(old_manifest - managed_files):
            target = safe_target(resources, Path(relative))
            if target.is_file() and not target.is_symlink():
                print(f"delete {target}") if args.verbose or args.dry_run else None
                stats.deleted += 1
                if not args.dry_run:
                    target.unlink()
                    remove_empty_parents(target, resources)

    manifest = json.dumps(
        {
            "schema_version": 1,
            "source": "claude-code-project-memory",
            "files": sorted(managed_files),
            "digests": {
                relative: sha256_bytes(data)
                for relative, data in sorted(desired.items())
            },
        },
        ensure_ascii=False,
        indent=2,
        sort_keys=True,
    ).encode() + b"\n"
    sync_file(manifest_path, manifest, args.dry_run, args.verbose, stats)

    mode = "Would sync" if args.dry_run else "Synced"
    print(
        f"{mode} {stats.projects} project(s): {stats.created} created, "
        f"{stats.updated} updated, {stats.unchanged} unchanged, "
        f"{stats.deleted} deleted, {stats.skipped} skipped."
    )
    if not args.dry_run and (stats.created or stats.updated or stats.deleted):
        print("Codex will consolidate the imported resources on a subsequent memory run.")
    return 0


def reverse_project_key(
    claude_home: Path, cwd: Path, mapping: dict[str, Path]
) -> str:
    projects_dir = claude_home / "projects"
    candidates = [
        key
        for key, mapped_cwd in mapping.items()
        if mapped_cwd == cwd and (projects_dir / key).is_dir()
    ]
    exact = claude_project_key(cwd)
    if exact in candidates:
        return exact
    return sorted(candidates)[0] if candidates else exact


def matches_reverse_filter(key: str, cwd: Path, filters: list[str]) -> bool:
    if not filters:
        return True
    normalized_cwd = os.path.normpath(str(cwd))
    return any(
        value == key or os.path.normpath(value) == normalized_cwd for value in filters
    )


def remove_reverse_project(
    project_dir: Path, dry_run: bool, verbose: bool, stats: SyncStats
) -> None:
    generated = project_dir / "memory" / CODEX_MEMORY_NAME
    try:
        content = generated.read_text(encoding="utf-8")
    except FileNotFoundError:
        content = None
    except (OSError, UnicodeDecodeError) as error:
        raise SystemExit(f"cannot read reverse-sync target {generated}: {error}") from error

    if content is not None and CODEX_MEMORY_MARKER in content:
        print(f"delete {generated}") if verbose or dry_run else None
        stats.deleted += 1
        if not dry_run:
            generated.unlink()

    index = project_dir / "memory" / "MEMORY.md"
    try:
        old_index = index.read_text(encoding="utf-8")
    except FileNotFoundError:
        return
    new_index = strip_codex_link(old_index)
    if new_index != old_index:
        sync_file(index, new_index.encode(), dry_run, verbose, stats)


def run_to_claude(args: argparse.Namespace) -> int:
    claude_home = args.claude_home.expanduser().resolve()
    codex_home = args.codex_home.expanduser().resolve()
    codex_registry = codex_home / "memories" / "MEMORY.md"
    try:
        registry_content = codex_registry.read_text(encoding="utf-8")
    except FileNotFoundError as error:
        raise SystemExit(f"Codex memory registry does not exist: {codex_registry}") from error
    except (OSError, UnicodeDecodeError) as error:
        raise SystemExit(f"cannot read Codex memory registry {codex_registry}: {error}") from error

    grouped = codex_task_groups(registry_content)
    mapping = collect_index_paths(claude_home)
    projects_dir = claude_home / "projects"
    manifest_path = claude_home / ".sync-codex-memory.json"
    old_projects = load_reverse_manifest(manifest_path)
    selected_keys: set[str] = set()
    desired_keys: set[str] = set()
    stats = SyncStats()

    for cwd, blocks in sorted(grouped.items(), key=lambda item: str(item[0])):
        key = reverse_project_key(claude_home, cwd, mapping)
        if not matches_reverse_filter(key, cwd, args.project):
            continue
        selected_keys.add(key)
        project_dir = projects_dir / key
        if not project_dir.is_dir() and not args.create_projects:
            print(
                f"warning: skip {cwd}: Claude project directory does not exist; "
                "use --create-projects to create it",
                file=sys.stderr,
            )
            stats.skipped += 1
            continue

        desired_keys.add(key)
        stats.projects += 1
        memory_dir = project_dir / "memory"
        generated = safe_target(memory_dir, Path(CODEX_MEMORY_NAME))
        sync_owned_file(
            generated,
            render_codex_memory(cwd, blocks),
            args.dry_run,
            args.verbose,
            stats,
        )

        index = memory_dir / "MEMORY.md"
        try:
            old_index = index.read_text(encoding="utf-8")
        except FileNotFoundError:
            old_index = "# Project Memory\n"
        except (OSError, UnicodeDecodeError) as error:
            raise SystemExit(f"cannot read Claude memory index {index}: {error}") from error
        sync_file(
            index,
            with_codex_link(old_index).encode(),
            args.dry_run,
            args.verbose,
            stats,
        )

    if args.project and not selected_keys:
        print("No matching project-scoped Codex memories found.", file=sys.stderr)
        return 1

    managed_projects = set(desired_keys)
    if args.project:
        managed_projects.update(old_projects - selected_keys)
    else:
        managed_projects.update(old_projects & (selected_keys - desired_keys))
    if not args.delete:
        managed_projects.update(old_projects)

    if args.delete:
        for key in sorted(old_projects - managed_projects):
            if not PROJECT_KEY_RE.fullmatch(key):
                continue
            remove_reverse_project(
                projects_dir / key, args.dry_run, args.verbose, stats
            )

    manifest = json.dumps(
        {
            "schema_version": 1,
            "source": "codex-project-memory",
            "projects": sorted(managed_projects),
        },
        ensure_ascii=False,
        indent=2,
        sort_keys=True,
    ).encode() + b"\n"
    sync_file(manifest_path, manifest, args.dry_run, args.verbose, stats)

    mode = "Would sync" if args.dry_run else "Synced"
    print(
        f"{mode} {stats.projects} project(s): {stats.created} created, "
        f"{stats.updated} updated, {stats.unchanged} unchanged, "
        f"{stats.deleted} deleted, {stats.skipped} skipped."
    )
    return 0


def validate_remote_args(args: argparse.Namespace) -> str | None:
    endpoint = args.source_ssh or args.target_ssh
    if endpoint is None:
        return None
    if not SSH_ENDPOINT_RE.fullmatch(endpoint):
        raise SystemExit(
            "SSH endpoint must use USER@HOST with no whitespace or shell syntax"
        )
    if not 1 <= args.ssh_port <= 65535:
        raise SystemExit("--ssh-port must be between 1 and 65535")
    return endpoint


def ssh_base(port: int) -> list[str]:
    return ["ssh", "-p", str(port), "-o", "BatchMode=yes"]


def scp_base(port: int) -> list[str]:
    return ["scp", "-P", str(port), "-o", "BatchMode=yes"]


def checked_command(
    command: list[str], *, capture: bool = False
) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            command,
            check=True,
            capture_output=capture,
            text=True,
        )
    except FileNotFoundError as error:
        raise SystemExit(f"required command is not installed: {command[0]}") from error
    except subprocess.CalledProcessError as error:
        if error.stdout:
            print(error.stdout, file=sys.stderr, end="")
        if error.stderr:
            print(error.stderr, file=sys.stderr, end="")
        raise SystemExit(
            f"command failed with exit status {error.returncode}: {command[0]}"
        ) from error


def remote_command(
    endpoint: str, port: int, arguments: list[str], *, capture: bool = False
) -> subprocess.CompletedProcess[str]:
    return checked_command(
        [*ssh_base(port), endpoint, shlex.join(arguments)], capture=capture
    )


def remote_home(endpoint: str, port: int) -> Path:
    result = checked_command(
        [*ssh_base(port), endpoint, 'printf "%s" "$HOME"'], capture=True
    )
    home = normalized_path(result.stdout.strip())
    if home is None:
        raise SystemExit(f"could not determine home directory on {endpoint}")
    return home


def create_remote_temp(endpoint: str, port: int) -> str:
    result = remote_command(
        endpoint,
        port,
        ["mktemp", "-d", "/tmp/sync-claude-memory.XXXXXX"],
        capture=True,
    )
    path = result.stdout.strip()
    if not re.fullmatch(r"/tmp/sync-claude-memory\.[A-Za-z0-9]+", path):
        raise SystemExit(f"remote mktemp returned an unsafe path: {path!r}")
    return path


def remove_remote_temp(endpoint: str, port: int, path: str) -> None:
    if not re.fullmatch(r"/tmp/sync-claude-memory\.[A-Za-z0-9]+", path):
        raise SystemExit(f"refusing to remove unsafe remote path: {path!r}")
    try:
        remote_command(endpoint, port, ["rm", "-rf", "--", path])
    except SystemExit as error:
        print(f"warning: could not remove remote staging directory: {error}", file=sys.stderr)


def copy_to_remote(
    source: Path, endpoint: str, port: int, destination: str
) -> None:
    checked_command(
        [*scp_base(port), "-r", str(source), f"{endpoint}:{destination}"]
    )


def copy_from_remote(
    endpoint: str, port: int, source: str, destination: Path
) -> None:
    checked_command(
        [*scp_base(port), "-r", f"{endpoint}:{source}", str(destination)]
    )


def staged_args(
    args: argparse.Namespace, claude_home: Path, codex_home: Path
) -> argparse.Namespace:
    values = vars(args).copy()
    values.update(
        {
            "claude_home": claude_home,
            "codex_home": codex_home,
            "source_ssh": None,
            "target_ssh": None,
        }
    )
    return argparse.Namespace(**values)


def remote_script_arguments(
    args: argparse.Namespace,
    runner: str,
    remote_script: str,
    claude_home: str,
    codex_home: str,
    *,
    extraction: bool = False,
) -> list[str]:
    command = [
        *(["uv", "run"] if runner == "uv" else ["python3"]),
        remote_script,
        "--direction",
        args.direction,
        "--claude-home",
        claude_home,
        "--codex-home",
        codex_home,
    ]
    for project in args.project:
        command.extend(("--project", project))
    if not extraction:
        if args.delete:
            command.append("--delete")
        if args.create_projects:
            command.append("--create-projects")
        if args.dry_run:
            command.append("--dry-run")
        if args.verbose:
            command.append("--verbose")
    return command


def remote_runner(endpoint: str, port: int) -> str:
    probe = (
        "if command -v uv >/dev/null 2>&1; then printf uv; "
        "elif command -v python3 >/dev/null 2>&1 && "
        "python3 -c 'import sys; raise SystemExit(sys.version_info < (3, 11))'; "
        "then printf python3; else exit 1; fi"
    )
    try:
        result = checked_command(
            [*ssh_base(port), endpoint, probe], capture=True
        )
    except SystemExit as error:
        raise SystemExit(
            f"{endpoint} needs uv or Python 3.11 or newer to run the sync tool"
        ) from error
    runner = result.stdout.strip()
    if runner not in {"uv", "python3"}:
        raise SystemExit(f"could not select a supported runtime on {endpoint}")
    return runner


def create_synthetic_claude_home(
    source_home: Path, destination: Path, filters: list[str]
) -> None:
    projects, warnings, _ = discover_projects(source_home, filters)
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)
    if filters and not projects:
        raise SystemExit("No matching Claude project memories found.")
    for project in projects:
        project_dir = destination / "projects" / project.key
        memory_dir = project_dir / "memory"
        memory_dir.mkdir(parents=True, exist_ok=True)
        for source in project.files:
            relative = source.relative_to(project.source_dir)
            target = safe_target(memory_dir, relative)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
        (project_dir / "sessions-index.json").write_text(
            json.dumps(
                {"version": 1, "originalPath": str(project.cwd), "entries": []},
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
        )


def create_synthetic_claude_from_extension(
    extension: Path, destination: Path
) -> None:
    resources = extension / "resources"
    if not resources.is_dir():
        raise SystemExit("remote sync did not produce an external-agent resource folder")
    for source_project in sorted(resources.iterdir()):
        if not source_project.is_dir() or not PROJECT_KEY_RE.fullmatch(source_project.name):
            continue
        scope = load_json(source_project / "scope.json")
        cwd = normalized_path(scope.get("cwd")) if isinstance(scope, dict) else None
        if cwd is None:
            print(f"warning: skip remote resource without valid scope: {source_project}")
            continue
        project_dir = destination / "projects" / source_project.name
        memory_dir = project_dir / "memory"
        memory_dir.mkdir(parents=True, exist_ok=True)
        for source in sorted(source_project.rglob("*.md")):
            if source.is_file() and not source.is_symlink():
                relative = source.relative_to(source_project)
                target = safe_target(memory_dir, relative)
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, target)
        (project_dir / "sessions-index.json").write_text(
            json.dumps(
                {"version": 1, "originalPath": str(cwd), "entries": []},
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )
            + "\n",
            encoding="utf-8",
        )


def run_remote_source(args: argparse.Namespace, endpoint: str) -> int:
    local_claude = args.claude_home.expanduser().resolve()
    local_codex = args.codex_home.expanduser().resolve()
    host_home = remote_home(endpoint, args.ssh_port)

    with tempfile.TemporaryDirectory(prefix="sync-claude-memory-") as temporary:
        staging = Path(temporary)
        if args.direction == "codex-to-claude":
            staged_codex = staging / "codex" / "memories"
            staged_codex.mkdir(parents=True)
            copy_from_remote(
                endpoint,
                args.ssh_port,
                str(host_home / ".codex" / "memories" / "MEMORY.md"),
                staged_codex / "MEMORY.md",
            )
            return run_to_claude(staged_args(args, local_claude, staging / "codex"))

        remote_temp = create_remote_temp(endpoint, args.ssh_port)
        try:
            runner = remote_runner(endpoint, args.ssh_port)
            remote_script = f"{remote_temp}/sync_claude_memory.py"
            copy_to_remote(Path(__file__).resolve(), endpoint, args.ssh_port, remote_script)
            result = remote_command(
                endpoint,
                args.ssh_port,
                remote_script_arguments(
                    args,
                    runner,
                    remote_script,
                    str(host_home / ".claude"),
                    f"{remote_temp}/codex",
                    extraction=True,
                ),
                capture=True,
            )
            if result.stderr:
                print(result.stderr, file=sys.stderr, end="")
            pulled = staging / "external_agent_import"
            copy_from_remote(
                endpoint,
                args.ssh_port,
                f"{remote_temp}/codex/memories/extensions/external_agent_import",
                pulled,
            )
        finally:
            remove_remote_temp(endpoint, args.ssh_port, remote_temp)

        staged_claude = staging / "claude"
        create_synthetic_claude_from_extension(pulled, staged_claude)
        return run_to_codex(staged_args(args, staged_claude, local_codex))


def run_remote_target(args: argparse.Namespace, endpoint: str) -> int:
    local_claude = args.claude_home.expanduser().resolve()
    local_codex = args.codex_home.expanduser().resolve()
    host_home = remote_home(endpoint, args.ssh_port)

    with tempfile.TemporaryDirectory(prefix="sync-claude-memory-") as temporary:
        staging = Path(temporary)
        if args.direction == "claude-to-codex":
            staged_source = staging / "claude"
            create_synthetic_claude_home(local_claude, staged_source, args.project)
        else:
            registry = local_codex / "memories" / "MEMORY.md"
            if not registry.is_file():
                raise SystemExit(f"Codex memory registry does not exist: {registry}")
            staged_source = staging / "codex"
            (staged_source / "memories").mkdir(parents=True)
            shutil.copy2(registry, staged_source / "memories" / "MEMORY.md")

        remote_temp = create_remote_temp(endpoint, args.ssh_port)
        try:
            runner = remote_runner(endpoint, args.ssh_port)
            remote_script = f"{remote_temp}/sync_claude_memory.py"
            remote_source = f"{remote_temp}/{staged_source.name}"
            copy_to_remote(Path(__file__).resolve(), endpoint, args.ssh_port, remote_script)
            copy_to_remote(staged_source, endpoint, args.ssh_port, remote_source)
            if args.direction == "claude-to-codex":
                claude_home = remote_source
                codex_home = str(host_home / ".codex")
            else:
                claude_home = str(host_home / ".claude")
                codex_home = remote_source
            remote_command(
                endpoint,
                args.ssh_port,
                remote_script_arguments(
                    args, runner, remote_script, claude_home, codex_home
                ),
            )
        finally:
            remove_remote_temp(endpoint, args.ssh_port, remote_temp)
    return 0


def main() -> int:
    args = parse_args()
    endpoint = validate_remote_args(args)
    if args.source_ssh and endpoint:
        return run_remote_source(args, endpoint)
    if args.target_ssh and endpoint:
        return run_remote_target(args, endpoint)
    if args.direction == "codex-to-claude":
        return run_to_claude(args)
    return run_to_codex(args)


if __name__ == "__main__":
    raise SystemExit(main())
